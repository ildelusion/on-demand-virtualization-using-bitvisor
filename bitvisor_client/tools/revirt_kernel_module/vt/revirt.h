void update_kernel_page_table(void)
{
	unsigned long *level4pt_base_address = (unsigned long*)LEVEL4PT_BASE_ADDRESS;	
	unsigned long *level3pt_base_address = NULL;

	level3pt_base_address = (unsigned long*)*(level4pt_base_address + PDPTE_ENTRY_NUM);
	level3pt_base_address = (unsigned long*)((unsigned long)level3pt_base_address & 0xfffff000);
	level3pt_base_address = (unsigned long*)((unsigned long)level3pt_base_address | 0xffffffff80000000);

	*(level3pt_base_address + PDE_ENTRY_NUM) = 0x40000000 | PDE_G_BIT | PDE_PS_BIT | PTE_P_BIT | PTE_RW_BIT;
}

